import type { Result } from "@/recommendation-engine";

// Формирует запрос к ИИ. Отправляются ТОЛЬКО баллы и тексты выбранных ответов:
// без имени, почты и других личных данных.
export function buildPrompt(result: Result): { system: string; user: string } {
  const system =
    "Ты — доброжелательный помощник по профориентации для школьников Казахстана. " +
    "Пиши по-русски, просто и коротко (до 200 слов). Не выдумывай статистику, зарплаты и прогнозы рынка труда. " +
    "Напомни, что тест — не научная диагностика и решение принимает человек.";
  const lines = result.top.map(
    (d, i) =>
      `${i + 1}. ${d.name}: ${d.score} из ${d.max} баллов. Ответы: ` +
      d.contributions.slice(0, 3).map((c) => `«${c.optionText}»`).join("; "),
  );
  const profs = result.professions.slice(0, 3).map((p) => p.profession.title).join(", ");
  const user =
    "Результаты теста по профориентации:\n" + lines.join("\n") +
    `\nПодходящие профессии по расчёту: ${profs}.\n` +
    "Объясни, почему именно эти направления подходят, предложи 2 способа проверить интерес на практике " +
    "и скажи, какие человеческие навыки пригодятся рядом с ИИ.";
  return { system, user };
}
