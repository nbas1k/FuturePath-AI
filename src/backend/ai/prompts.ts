import type { Result } from "@/recommendation-engine";
import type { Profession } from "@/data/professions";
import type { AiPrompt } from "./provider";

// Общие правила для всех запросов к ИИ.
const RULES =
  "Ты помощник по профориентации для школьников и студентов Казахстана. Пиши по-русски, простыми словами. " +
  "Используй ТОЛЬКО данные, которые даны в сообщении. Не придумывай статистику, цифры, зарплаты и данные о рынке труда. " +
  "Прогнозы описывай как предположения, а не как факты. Не пиши проценты и числа баллов. " +
  "Не меняй результаты теста: они уже подсчитаны. Ответ верни ТОЛЬКО как один JSON-объект, без текста вне JSON.";

// Что именно уходит модели из результатов теста: только направления, проценты и тексты выбранных ответов.
// Имя пользователя и id профиля не передаются.
export function resultData(result: Result) {
  return {
    топ_направления: result.top.map((d) => ({
      название: d.name,
      процент_совпадения: d.percent,
      ответы_которые_повлияли: d.contributions.slice(0, 4).map((c) => c.optionText),
    })),
    все_направления: result.directions.map((d) => ({ название: d.name, процент_совпадения: d.percent })),
    профессии_по_расчёту: result.professions.slice(0, 5).map((p) => p.profession.title),
  };
}

export function analysisPrompt(result: Result): AiPrompt {
  return {
    system:
      RULES +
      ' Формат JSON: {"summary": "краткое резюме 2–4 предложения", "strengths": ["2–5 сильных сторон"], ' +
      '"interests": ["1–5 интересов, видных из ответов"], "skills": ["2–6 навыков, которые стоит развивать"], ' +
      '"missingSkills": ["2–5 компетенций, которые нужны выбранным профессиям; что у человека уже есть, неизвестно"], ' +
      '"resources": ["1–4 вида образовательных ресурсов, например «курсы по основам программирования», без ссылок и без названий конкретных курсов"]}. ' +
      "Навыки человека оцениваются только по ответам теста, это не измеренный уровень. Не добавляй ссылки.",
    user: "Данные теста (уже подсчитаны, менять нельзя):\n" + JSON.stringify(resultData(result), null, 2) +
      "\nСделай персональный анализ: сильные стороны, интересы и навыки.",
  };
}

export function roadmapPrompt(result: Result): AiPrompt {
  return {
    system:
      RULES +
      ' Формат JSON: {"days": [ {"day": 1, "title": "короткое название до 120 символов", "task": "конкретное задание до 400 символов"} ]}. ' +
      "Ровно 30 элементов, номера day от 1 до 30 по порядку. Каждое задание занимает 15–30 минут, выполнимо школьником самостоятельно, " +
      "без платных курсов и без конкретных цен.",
    user: "Данные теста (уже подсчитаны, менять нельзя):\n" + JSON.stringify(resultData(result), null, 2) +
      "\nСоставь персональный план развития на 30 дней с конкретными заданиями, учитывающими эти направления.",
  };
}

export function simulatorPrompt(profession: Profession, topDirections: string[]): AiPrompt {
  const data = {
    профессия: profession.title,
    описание: profession.description,
    задачи: profession.tasks,
    навыки: profession.skills,
    что_ИИ_может_автоматизировать_по_каталогу: profession.aiAutomates,
    человеческие_навыки_по_каталогу: profession.humanSkills,
    влияние_ИИ_по_каталогу: profession.aiImpact,
    направления_пользователя: topDirections,
  };
  return {
    system:
      RULES +
      ' Формат JSON: {"summary": "как ИИ может изменить эту профессию, 2–4 предложения, качественно", ' +
      '"automates": ["2–6 задач, которые ИИ может взять на себя"], "humanSkills": ["2–6 навыков, которые останутся важными"], ' +
      '"advice": "что можно сделать сейчас, до 600 символов"}. Опирайся на данные каталога.',
    user: "Данные профессии:\n" + JSON.stringify(data, null, 2) + "\nРазбери, как ИИ может изменить задачи этой профессии.",
  };
}
