// Версия содержимого плана. Если поменяете тексты заданий или правила сборки, увеличьте её:
// тогда старые отметки перестанут относиться к новому плану (они не перенесутся на другие задания).
export const PLAN_VERSION = "v1";

export type PlanDay = { day: number; taskId: string; task: string; direction: DirectionId | null };

// Собирает план из ровно 30 заданий: 4 общих + 8/6/4 по топ-3 направлениям + 8 общих.
// taskId — постоянный идентификатор задания внутри версии плана (не зависит от номера дня).
export function buildPlan(top: DirectionId[]): PlanDay[] {
  const parts: { taskId: string; task: string; direction: DirectionId | null }[] = [];
  COMMON_START.forEach((task, i) => parts.push({ taskId: `start-${i + 1}`, task, direction: null }));
  const counts = [8, 6, 4];
  top.slice(0, 3).forEach((dir, rank) => {
    DIRECTION_TASKS[dir].slice(0, counts[rank]).forEach((task, i) => parts.push({ taskId: `${dir}-${i + 1}`, task, direction: dir }));
  });
  COMMON_END.forEach((task, i) => parts.push({ taskId: `end-${i + 1}`, task, direction: null }));
  return parts.slice(0, 30).map((p, i) => ({ day: i + 1, ...p }));
}

// Ключ плана = версия + три направления по порядку, например "v1:it+design+business".
// Отметки хранятся под этим ключом: при новом тесте (другие направления) старые отметки не применяются.
export function planKeyFor(top: DirectionId[]): string {
  return `${PLAN_VERSION}:${top.slice(0, 3).join("+")}`;
}

// Разбирает ключ обратно в направления. Возвращает null, если ключ неверный (защита от подделки запроса).
export function parsePlanKey(key: unknown): DirectionId[] | null {
  if (typeof key !== "string") return null;
  const [version, part] = key.split(":");
  if (version !== PLAN_VERSION || !part) return null;
  const dirs = part.split("+");
  const valid = dirs.length === 3 && new Set(dirs).size === 3 && dirs.every((d) => Object.prototype.hasOwnProperty.call(DIRECTION_TASKS, d));
  return valid ? (dirs as DirectionId[]) : null;
}
